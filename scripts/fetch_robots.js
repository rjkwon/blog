import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Pulls updated list of AI training scrapers from knownagents.com and adds them to static/robots.txt

const API_URL = "https://api.knownagents.com/robots-txts";
const AGENT_TYPES = ["AI Data Scraper"];
const MARKER = "# --- Generated by scripts/fetch_robots.js, edits below are overwritten ---";

const robotsPath = path.join(__dirname, "..", "static", "robots.txt");

const fetchAndSave = async () => {
  const token = process.env.BOT_TRACKING_TOKEN;
  if (!token) {
    console.log("BOT_TRACKING_TOKEN not set, keeping existing robots.txt");
    return;
  }

  try {
    const res = await fetch(API_URL, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ agent_types: AGENT_TYPES, disallow: "/" }),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);

    const rules = (await res.text()).trim();
    if (!rules.includes("User-agent:")) throw new Error("Unexpected response");

    const current = fs.readFileSync(robotsPath, "utf8");
    const manual = current.split(MARKER)[0].trimEnd();

    fs.writeFileSync(robotsPath, `${manual}\n\n${MARKER}\n\n${rules}\n`);
    const count = (rules.match(/^User-agent:/gim) || []).length;
    console.log(`Saved ${count} blocked agents to static/robots.txt`);
  } catch (err) {
    console.error("Error fetching robots.txt rules, keeping existing file:", err.message);
  }
};

fetchAndSave();
